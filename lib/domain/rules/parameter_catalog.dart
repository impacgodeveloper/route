enum ParameterCategory {
  timeWindows('Time windows'),
  cost('Operating cost'),
  distance('Distance & detour'),
  travelTime('Travel time'),
  traffic('Traffic (demo)'),
  capacity('Capacity & seating'),
  compatibility('Passenger compatibility'),
  availability('Driver & vehicle availability'),
  evEmissions('EV & emissions'),
  preferences('Customer & luxury preferences'),
  safety('Safety & guard'),
  geography('Geography, parking & depots'),
  reliability('Reliability & history (demo)'),
  shift('Shift constraints'),
  customerPolicy('Customer policy'),
  utilization('Utilization & deadheading');

  const ParameterCategory(this.label);
  final String label;
}

/// Definition of a named optimization parameter.
///
/// [usedByDemoOptimizer] marks the subset the local demo optimizer
/// actually reads. Everything else is a catalog entry for future
/// integrations — it is NOT connected to live data.
class ParameterDefinition {
  const ParameterDefinition({
    required this.key,
    required this.name,
    required this.description,
    required this.unit,
    required this.defaultValue,
    required this.min,
    required this.max,
    required this.category,
    this.activeByDefault = false,
    this.usedByDemoOptimizer = false,
    this.hardConstraint = false,
    this.dataSource = 'Future integration',
  });

  final String key;
  final String name;
  final String description;
  final String unit;
  final double defaultValue;
  final double min;
  final double max;
  final ParameterCategory category;
  final bool activeByDefault;
  final bool usedByDemoOptimizer;
  final bool hardConstraint;
  final String dataSource;

  bool get isEditable => usedByDemoOptimizer;
}


const telematicsDemoLabel =
    'Simulated telematics — no GPS/OBD hardware connected';

enum TelematicsTab {
  live('Live vehicles'),
  events('Events'),
  geofences('Geofences'),
  simulate('Demo simulation');

  const TelematicsTab(this.label);
  final String label;

  static TelematicsTab parse(String? s) =>
      TelematicsTab.values.where((t) => t.name == s).firstOrNull ??
      TelematicsTab.live;
}

StatusTone eventTone(VehicleEventType t) => switch (t) {
  VehicleEventType.speeding ||
  VehicleEventType.restrictedEntry => StatusTone.danger,
  VehicleEventType.diagnosticFault => StatusTone.warning,
  VehicleEventType.harshBraking => StatusTone.warning,
  VehicleEventType.geofenceExit ||
  VehicleEventType.routeDeviation => StatusTone.info,
};

/// Telematics & geofences (all data simulated from trip progress).
class TelematicsPage extends ConsumerStatefulWidget {
  const TelematicsPage({super.key, this.initialTab});
  final String? initialTab;

  @override
  ConsumerState<TelematicsPage> createState() => _TelematicsPageState();
}

class _TelematicsPageState extends ConsumerState<TelematicsPage> {
  late TelematicsTab _tab = TelematicsTab.parse(widget.initialTab);

  @override
  void didUpdateWidget(TelematicsPage old) {
    super.didUpdateWidget(old);
    if (old.initialTab != widget.initialTab && widget.initialTab != null) {
      _tab = TelematicsTab.parse(widget.initialTab);
    }
  }

  @override
  Widget build(BuildContext context) {
    final data = ref.watch(dataProvider);
    final open = data.openVehicleEvents.length;
    return AdminPage(
      title: 'Telematics & geofences',
      subtitle:
          'Vehicle position, speed, diagnostics and geofence monitoring. Policy speed limit ${data.policy.speedLimitKmh} km/h · route corridor ±${data.policy.routeCorridorKm.toStringAsFixed(1)} km.',
      actions: [
        OutlinedButton.icon(
          onPressed: () => runAndShow(
            context,
            ref.read(servicesProvider).telematics.scan(),
            successMessage: 'Scan complete',
          ),
          icon: const Icon(Icons.radar_rounded),
          label: const Text('Run scan'),
        ),
      ],
      children: [
        const InlineBanner(
          tone: StatusTone.info,
          title: telematicsDemoLabel,
          message:
              'Positions and speeds are derived from trip progress on the fictional demo plane. Events are generated by the local rules engine or the demo simulation panel.',
          icon: Icons.sensors_off_outlined,
        ),
        const SizedBox(height: AppSpace.md),
        FilterChipBar<TelematicsTab>(
          options: TelematicsTab.values,
          selected: _tab,
          onSelected: (t) => setState(() => _tab = t),
          labelOf: (t) =>
              t == TelematicsTab.events ? 'Events · $open open' : t.label,
        ),
        const SizedBox(height: AppSpace.md),
        switch (_tab) {
          TelematicsTab.live => const _LiveView(),
          TelematicsTab.events => const _EventsView(),
          TelematicsTab.geofences => const _GeofencesView(),
          TelematicsTab.simulate => const _SimulateView(),
        },
      ],
    );
  }
}

class _LiveView extends ConsumerWidget {
  const _LiveView();

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final data = ref.watch(dataProvider);
    final services = ref.read(servicesProvider);
    final fleet = services.telematics.fleet();
    final limit = data.policy.speedLimitKmh;
    final t = Theme.of(context).textTheme;
    final corridors = <List<Offset>>[
      for (final s in fleet)
        if (s.trip != null && s.trip!.status.isActive)
          [
            for (final st in data.trips.stopsOf(s.trip!))
              if (data.location(st.locationId) case final l?)
                Offset(l.demoX, l.demoY),
          ],
    ];

    final table = AdaptiveTable<VehicleTelemetry>(
      rows: fleet,
      onRowTap: (s) => context.go('/fleet/vehicles/${s.vehicle.id}'),
      columns: [
        TableCol(
          'Vehicle',
          (s) => Text('Vehicle ${s.vehicle.vehicleCode}', style: t.titleSmall),
          flex: 2,
        ),
        TableCol(
          'Status',
          (s) => StatusBadge(
            s.status,
            tone: s.moving ? StatusTone.teal : StatusTone.neutral,
            dense: true,
          ),
          flex: 2,
        ),
        TableCol(
          'Speed',
          (s) => Text(
            '${s.speedKmh.round()} / $limit km/h',
            style: TextStyle(
              color: s.speedKmh > limit ? AppColors.danger : null,
              fontWeight: s.speedKmh > limit ? FontWeight.w700 : null,
            ),
          ),
          flex: 2,
          numeric: true,
        ),
        TableCol(
          'Position',
          (s) => Text(
            s.positionLabel,
            maxLines: 2,
            overflow: TextOverflow.ellipsis,
          ),
          flex: 3,
        ),
        TableCol('Trip', (s) => Text(s.trip?.tripCode ?? '—'), flex: 2),
        TableCol(
          'Energy · odometer',
          (s) => Text(
            '${s.vehicle.batteryOrFuelPercent == null ? '—' : '${s.vehicle.batteryOrFuelPercent}%'} · ${Fmt.number(s.vehicle.odometerKm.round())} km',
          ),
          flex: 3,
        ),
        TableCol(
          'Alerts',
          (s) => Text(
            [
              if (s.openEvents.isNotEmpty) '${s.openEvents.length} open',
              if (s.diagnosticCodes.isNotEmpty)
                '${s.diagnosticCodes.length} DTC',
            ].join(' · ').ifEmpty('None'),
            style: TextStyle(
              color: s.openEvents.isEmpty && s.diagnosticCodes.isEmpty
                  ? AppColors.textMuted
                  : AppColors.danger,
            ),
          ),
          flex: 2,
        ),
        TableCol(
          'Updated',
          (s) => Text(Fmt.ago(s.lastUpdate, data.now)),
          flex: 2,
          numeric: true,
        ),
      ],
      mobileCard: (s) => Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            children: [
              Expanded(
                child: Text(
                  'Vehicle ${s.vehicle.vehicleCode}',
                  style: t.titleSmall,
                ),
              ),
              StatusBadge(
                s.status,
                tone: s.moving ? StatusTone.teal : StatusTone.neutral,
                dense: true,
              ),
            ],
          ),
          const SizedBox(height: 4),
          Text(
            '${s.speedKmh.round()} km/h (limit $limit) · ${s.positionLabel}',
            style: AppText.secondary(context),
          ),
          Text(
            '${s.trip?.tripCode ?? 'No trip'} · updated ${Fmt.ago(s.lastUpdate, data.now)}${s.diagnosticCodes.isEmpty ? '' : ' · ${s.diagnosticCodes.length} DTC'}${s.openEvents.isEmpty ? '' : ' · ${s.openEvents.length} open alert(s)'}',
            style: AppText.muted(context),
          ),
        ],
      ),
    );

    final map = PanelCard(
      title: 'Fleet map',
      subtitle: 'Simulated positions, geofences and active-trip corridors',
      child: TelematicsMap(
        vehicles: [
          for (final s in fleet)
            VehicleMarker(
              code: s.vehicle.vehicleCode,
              x: s.x,
              y: s.y,
              moving: s.moving,
              alert: s.openEvents.isNotEmpty,
            ),
        ],
        geofences: data.geofences,
        corridors: corridors,
        corridorKm: data.policy.routeCorridorKm,
      ),
    );
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        table,
        const SizedBox(height: AppSpace.md),
        map,
      ],
    );
  }
}

enum _AckFilter { open, acknowledged, all }

class _EventsView extends ConsumerStatefulWidget {
  const _EventsView();

  @override
  ConsumerState<_EventsView> createState() => _EventsViewState();
}

class _EventsViewState extends ConsumerState<_EventsView> {
  VehicleEventType? _type;
  String? _vehicle;
  _AckFilter _ack = _AckFilter.open;

  Future<void> _acknowledge(VehicleEvent e) async {
    final result = await showDialog<(String, bool)>(
      context: context,
      builder: (_) => _AckDialog(event: e),
    );
    if (result == null || !mounted) return;
    await runAndShow(
      context,
      ref
          .read(servicesProvider)
          .telematics
          .acknowledge(e.id, note: result.$1, raiseIncident: result.$2),
    );
  }

  @override
  Widget build(BuildContext context) {
    final data = ref.watch(dataProvider);
    final t = Theme.of(context).textTheme;
    final events = data.vehicleEvents.where((e) {
      if (_type != null && e.type != _type) return false;
      if (_vehicle != null && e.vehicleId != _vehicle) return false;
      return switch (_ack) {
        _AckFilter.open => e.open,
        _AckFilter.acknowledged => !e.open,
        _AckFilter.all => true,
      };
    }).toList();
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Wrap(
          spacing: AppSpace.sm,
          runSpacing: AppSpace.sm,
          crossAxisAlignment: WrapCrossAlignment.center,
          children: [
            FilterChipBar<_AckFilter>(
              options: _AckFilter.values,
              selected: _ack,
              onSelected: (a) => setState(() => _ack = a),
              labelOf: (a) => switch (a) {
                _AckFilter.open => 'Open',
                _AckFilter.acknowledged => 'Acknowledged',
                _AckFilter.all => 'All',
              },
            ),
            SizedBox(
              width: 220,
              child: DropdownButtonFormField<VehicleEventType?>(
                isExpanded: true,
                initialValue: _type,
                decoration: const InputDecoration(labelText: 'Event type'),
                items: [
                  const DropdownMenuItem(value: null, child: Text('All types')),
                  for (final ty in VehicleEventType.values)
                    DropdownMenuItem(value: ty, child: Text(ty.label)),
                ],
                onChanged: (v) => setState(() => _type = v),
              ),
            ),
            SizedBox(
              width: 180,
              child: DropdownButtonFormField<String?>(
                isExpanded: true,
                initialValue: _vehicle,
                decoration: const InputDecoration(labelText: 'Vehicle'),
                items: [
                  const DropdownMenuItem(
                    value: null,
                    child: Text('All vehicles'),
                  ),
                  for (final v in data.vehicles)
                    DropdownMenuItem(
                      value: v.id,
                      child: Text('Vehicle ${v.vehicleCode}'),
                    ),
                ],
                onChanged: (v) => setState(() => _vehicle = v),
              ),
            ),
          ],
        ),
        const SizedBox(height: AppSpace.md),
        if (events.isEmpty)
          EmptyState(
            icon: Icons.notifications_off_outlined,
            title: 'No events',
            message: _ack == _AckFilter.open
                ? 'No open telematics events. Use the demo simulation panel to generate one.'
                : 'No events match these filters.',
            compact: true,
          )
        else
          for (final e in events)
            Padding(
              padding: const EdgeInsets.only(bottom: AppSpace.sm),
              child: AppCard(
                padding: const EdgeInsets.all(AppSpace.md),
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.stretch,
                  children: [
                    Row(
                      children: [
                        StatusBadge(
                          e.type.label,
                          tone: eventTone(e.type),
                          dense: true,
                        ),
                        const SizedBox(width: AppSpace.xs),
                        Expanded(
                          child: Text(
                            'Vehicle ${data.vehicle(e.vehicleId)?.vehicleCode ?? e.vehicleId} · ${e.id}',
                            style: t.titleSmall,
                            overflow: TextOverflow.ellipsis,
                          ),
                        ),
                        Text(
                          Fmt.ago(e.occurredAt, data.now),
                          style: AppText.muted(context),
                        ),
                      ],
                    ),
                    const SizedBox(height: 4),
                    Text(e.description),
                    if (e.value != null && e.limit != null)
                      Text(
                        'Measured ${e.value!.toStringAsFixed(0)} vs limit ${e.limit!.toStringAsFixed(0)}',
                        style: AppText.muted(context),
                      ),
                    const SizedBox(height: AppSpace.xs),
                    Wrap(
                      spacing: AppSpace.xs,
                      runSpacing: AppSpace.xs,
                      crossAxisAlignment: WrapCrossAlignment.center,
                      children: [
                        if (e.simulated)
                          const StatusBadge('Simulated', dense: true),
                        if (!e.open)
                          StatusBadge(
                            'Acknowledged ${Fmt.ago(e.acknowledgedAt!, data.now)}',
                            tone: StatusTone.success,
                            dense: true,
                          ),
                        if (e.tripId != null)
                          TextButton(
                            onPressed: () =>
                                context.go('/fleet/dispatch/trip/${e.tripId}'),
                            child: Text('Trip ${e.tripId}'),
                          ),
                        if (e.incidentId != null)
                          TextButton(
                            onPressed: () => context.go(
                              '/fleet/monitoring/incident/${e.incidentId}',
                            ),
                            child: Text('Incident ${e.incidentId}'),
                          ),
                        if (e.open)
                          FilledButton(
                            onPressed: () => _acknowledge(e),
                            child: const Text('Acknowledge…'),
                          ),
                      ],
                    ),
                  ],
                ),
              ),
            ),
      ],
    );
  }
}

class _AckDialog extends StatefulWidget {
  const _AckDialog({required this.event});
  final VehicleEvent event;

  @override
  State<_AckDialog> createState() => _AckDialogState();
}

class _AckDialogState extends State<_AckDialog> {
  final _note = TextEditingController();
  bool _incident = false;

  @override
  void dispose() {
    _note.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => AlertDialog(
    title: Text('Acknowledge ${widget.event.type.label.toLowerCase()}'),
    content: SizedBox(
      width: 440,
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Text(widget.event.description),
          const SizedBox(height: AppSpace.sm),
          TextField(
            key: const Key('ackNote'),
            controller: _note,
            minLines: 2,
            maxLines: 3,
            decoration: const InputDecoration(
              labelText: 'Note (optional)',
              alignLabelWithHint: true,
            ),
          ),
          CheckboxListTile(
            contentPadding: EdgeInsets.zero,
            value: _incident,
            onChanged: (v) => setState(() => _incident = v ?? false),
            title: const Text('Raise an incident'),
            subtitle: const Text(
              'Creates a local incident in Monitoring & Incidents.',
            ),
          ),
        ],
      ),
    ),
    actions: [
      TextButton(
        onPressed: () => Navigator.pop(context),
        child: const Text('Cancel'),
      ),
      FilledButton(
        onPressed: () => Navigator.pop(context, (_note.text, _incident)),
        child: const Text('Acknowledge'),
      ),
    ],
  );
}


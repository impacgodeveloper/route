class _SimulateView extends ConsumerStatefulWidget {
  const _SimulateView();

  @override
  ConsumerState<_SimulateView> createState() => _SimulateViewState();
}

class _SimulateViewState extends ConsumerState<_SimulateView> {
  String? _vehicle;
  VehicleEventType _type = VehicleEventType.speeding;
  final _value = TextEditingController();
  final _code = TextEditingController(text: 'P0300 · Random misfire detected');
  String? _outcome;
  bool _outcomeOk = true;
  bool _busy = false;

  @override
  void dispose() {
    _value.dispose();
    _code.dispose();
    super.dispose();
  }

  String? get _valueLabel => switch (_type) {
    VehicleEventType.speeding => 'Speed (km/h)',
    VehicleEventType.routeDeviation => 'Offset from route (km)',
    VehicleEventType.geofenceExit => 'Distance outside area (km)',
    _ => null,
  };

  Future<void> _run() async {
    final data = ref.read(dataProvider);
    final vehicleId = _vehicle ?? data.vehicles.first.id;
    setState(() => _busy = true);
    final r = await ref
        .read(servicesProvider)
        .telematics
        .simulate(
          vehicleId,
          _type,
          value: double.tryParse(_value.text.trim()),
          code: _type == VehicleEventType.diagnosticFault ? _code.text : null,
        );
    if (!mounted) return;
    setState(() {
      _busy = false;
      if (!r.isOk) {
        _outcomeOk = false;
        _outcome = r.message;
      } else {
        final events = r.valueOrNull ?? const <VehicleEvent>[];
        _outcomeOk = true;
        _outcome = events.isEmpty
            ? 'Nothing generated — no new event: the same condition already has an open event, the sample is within limits, or alerts are disabled in the fleet policy.'
            : 'Generated ${events.map((e) => '${e.id} (${e.type.label})').join(', ')}. See the Events tab.';
      }
    });
  }

  @override
  Widget build(BuildContext context) {
    final data = ref.watch(dataProvider);
    _vehicle ??=
        data.vehicles.where((v) => v.id == 'C2').firstOrNull?.id ??
        data.vehicles.first.id;
    return PanelCard(
      title: 'Demo simulation',
      subtitle:
          'Inject a simulated telematics sample. Rules (speed limit, geofences, corridor, dedupe) run exactly as for live data would.',
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          FormRow(
            children: [
              DropdownButtonFormField<String>(
                key: const Key('simVehicle'),
                isExpanded: true,
                initialValue: _vehicle,
                decoration: const InputDecoration(labelText: 'Vehicle'),
                items: [
                  for (final v in data.vehicles)
                    DropdownMenuItem(
                      value: v.id,
                      child: Text('Vehicle ${v.vehicleCode}'),
                    ),
                ],
                onChanged: (v) => setState(() => _vehicle = v),
              ),
              DropdownButtonFormField<VehicleEventType>(
                key: const Key('simType'),
                isExpanded: true,
                initialValue: _type,
                decoration: const InputDecoration(labelText: 'Event'),
                items: [
                  for (final ty in VehicleEventType.values)
                    DropdownMenuItem(value: ty, child: Text(ty.label)),
                ],
                onChanged: (v) => setState(() => _type = v ?? _type),
              ),
            ],
          ),
          const SizedBox(height: AppSpace.sm),
          if (_valueLabel != null)
            TextField(
              key: const Key('simValue'),
              controller: _value,
              keyboardType: TextInputType.number,
              decoration: InputDecoration(
                labelText: _valueLabel,
                helperText: _type == VehicleEventType.speeding
                    ? 'Default: limit + 18 km/h'
                    : 'Leave empty for a sensible default',
              ),
            ),
          if (_type == VehicleEventType.diagnosticFault)
            TextField(
              key: const Key('simCode'),
              controller: _code,
              decoration: const InputDecoration(
                labelText: 'Diagnostic trouble code',
              ),
            ),
          const SizedBox(height: AppSpace.md),
          Wrap(
            spacing: AppSpace.xs,
            runSpacing: AppSpace.xs,
            children: [
              FilledButton.icon(
                key: const Key('simRun'),
                onPressed: _busy ? null : _run,
                icon: const Icon(Icons.science_outlined),
                label: const Text('Simulate'),
              ),
              OutlinedButton.icon(
                onPressed: () => runAndShow(
                  context,
                  ref.read(servicesProvider).telematics.scan(),
                  successMessage: 'Scan complete',
                ),
                icon: const Icon(Icons.radar_rounded),
                label: const Text('Run scan'),
              ),
            ],
          ),
          if (_outcome != null) ...[
            const SizedBox(height: AppSpace.md),
            InlineBanner(
              tone: _outcomeOk ? StatusTone.info : StatusTone.danger,
              title: _outcomeOk ? 'Simulation result' : 'Not simulated',
              message: _outcome,
            ),
          ],
          const SizedBox(height: AppSpace.sm),
          const SimulatedNote(telematicsDemoLabel),
        ],
      ),
    );
  }
}

